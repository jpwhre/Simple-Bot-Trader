_current = None


def detect_language():
    """OS / keyboard locale -> 2-letter code ('en' fallback). Never IP."""
    code = ''
    try:
        code = _locale.getlocale()[0] or ''
    except Exception:
        pass
    if not code:
        for var in ('LANGUAGE', 'LC_ALL', 'LC_MESSAGES', 'LANG'):
            v = os.environ.get(var) or ''
            if v:
                code = v.split('.')[0]
                break
    if not code:
        return 'en'
    lang = code.replace('_', '-').split('-')[0].lower()
    return lang if lang in _STRINGS else 'en'


def set_language(code):
    global _current
    _current = (code or 'en').lower()


def current_language():
    global _current
    if _current is None:
        _current = detect_language()
    return _current


def tr(template, **kwargs):
    """Translate a UI string. English strings are the keys; a missing entry
    falls back to English (the app always works fully). Optional {placeholders}
    are formatted after translation."""
    lang = current_language()
    d = _STRINGS.get(lang) or {}
    s = d.get(template, template)
    return s.format(**kwargs) if kwargs else s
